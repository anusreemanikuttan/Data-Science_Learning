

# Swapping of two numbers
# ========================================

num1 = int(input("Enter first number: "))
num2 = int(input("Enter second number: "))
print("Before Swapping -------")
print("Number 1 is :",num1)
print("Number 2 is :",num2)

print("After Swapping -------")

temp = num1
num1 = num2
num2 = temp

print("Number 1 is :",num1)
print("Number 2 is :",num2)

